-- Під час повторного запуску таблиці не видаляються.
CREATE TABLE IF NOT EXISTS services (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(64) NOT NULL UNIQUE,
  title VARCHAR(120) NOT NULL,
  category VARCHAR(64) NOT NULL,
  description TEXT NOT NULL,
  duration_min INTEGER NOT NULL CHECK (duration_min BETWEEN 10 AND 300),
  price_uah INTEGER NOT NULL CHECK (price_uah >= 0),
  image_key VARCHAR(32) NOT NULL DEFAULT 'glow',
  position INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS appointments (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  reference VARCHAR(24) UNIQUE NOT NULL,
  service_id INTEGER NOT NULL REFERENCES services(id),
  client_name VARCHAR(80) NOT NULL,
  client_phone VARCHAR(20) NOT NULL,
  preferred_date DATE NOT NULL,
  preferred_time TIME NOT NULL,
  comment VARCHAR(500) NOT NULL DEFAULT '',
  status VARCHAR(24) NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'confirmed', 'cancelled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS appointments_date_idx ON appointments (preferred_date);
